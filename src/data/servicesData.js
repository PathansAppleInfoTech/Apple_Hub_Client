export function formatPrice(pkg) {
    if (pkg.price == null) return pkg.priceSuffix || 'Custom';
    return `\u20B9${pkg.price.toLocaleString('en-IN')}${pkg.priceSuffix ? ` ${pkg.priceSuffix}` : '/-'}`;
}